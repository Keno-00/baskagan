const assert=require('node:assert/strict');
const {capture,label,pending,consume,signature}=require('../ui/comment_context.js');
const first={contextId:'stable-a',id:1,source:'Chat',conversation:'c',message:'m',quote:'hello 😀',text:'Initial feedback',from:0,to:8,onSave(){}};
const second={contextId:'stable-b',id:1,source:'C:/project/main.rs',quote:'fn main() {}',text:'Code feedback',from:0,to:12,lineFrom:1,lineTo:2};
assert.deepEqual(capture([first,second],[]),[]);
const sent=capture([first,second],['stable-a']);assert.equal(sent.length,1);assert.equal(sent[0].id,'stable-a');assert.equal(sent[0].source,'chat');assert.equal(sent[0].to,8);assert.equal(sent[0].onSave,undefined);
first.text='Later edit';assert.equal(sent[0].text,'Initial feedback','sent context must stay immutable');assert.equal(capture([first],['stable-a'])[0].text,'Later edit');
assert.deepEqual(capture([second],['stable-a']),[],'reused visible ID must not select a new comment');
assert.equal(capture([second],['stable-b','stable-b']).length,1);
assert.equal(label(second),'L1–L2');assert.equal(label({...first,quote:'a'.repeat(80)}).length,50);
const many=Array.from({length:25},(_,i)=>({...first,contextId:`item-${i}`}));assert.throws(()=>capture(many,many.map(i=>i.contextId)),/24/);
console.log('Explicit annotation selection, stable identity, immutable snapshots and bounds passed.');
const queued={...first,contextId:'pending-chat',text:'Send this without a typed message'};
assert.deepEqual(pending([queued]),[queued],'saved comments automatically enter the draft');
const submitted=capture([queued],pending([queued]).map(item=>item.contextId));
consume([queued],submitted);
assert.deepEqual(pending([queued]),[],'send clears pending composer comments without deleting annotations');
assert.equal(queued.text,'Send this without a typed message');
const reopened=JSON.parse(JSON.stringify(queued));
assert.deepEqual(pending([reopened]),[],'sent comments stay cleared after reopening');
reopened.text='Updated feedback';
assert.deepEqual(pending([reopened]),[reopened],'editing a sent comment queues the new version');
reopened.contextDismissedSnapshot=signature(reopened);
assert.deepEqual(pending([reopened]),[],'removing a draft chip does not silently add it back');
reopened.text='Another update';
assert.deepEqual(pending([reopened]),[reopened]);
const legacy={...first,contextId:'legacy-comment'};
const legacySnapshot=capture([legacy],['legacy-comment'])[0];
const sortedSnapshot=Object.fromEntries(Object.entries(legacySnapshot).sort(([a],[b])=>a.localeCompare(b)));
assert.deepEqual(pending([legacy],[{comments:[sortedSnapshot]}]),[],'older sent comments remain consumed regardless of JSON property order');
assert.equal(pending([second], [{comments:submitted}]).length,1,'a reused display number is still a new annotation');
console.log('Comment-only draft queue, send clearing, reopen, edit and migration checks passed.');
