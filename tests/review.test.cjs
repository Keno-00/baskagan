const assert=require('node:assert/strict');
const {normalizeText,pathKey,diff,applicationIssue}=require('../ui/review.js');
assert.equal(normalizeText('\ufeffone\r\ntwo\r\n'),'one\ntwo\n');
assert.equal(pathKey('C:\\Project\\.\\src\\main.rs'),pathKey('c:/project/src/main.rs'));
assert.equal(pathKey('\\\\?\\C:\\Project\\main.rs'),pathKey('c:/project/main.rs'));
assert.notEqual(pathKey('/project/A.rs'),pathKey('/project/a.rs'));
const rows=diff('same\nold\ntail\n','same\nnew\ntail\n');
assert.deepEqual(rows.filter(r=>r.kind==='remove').map(r=>r.text),['old']);
assert.deepEqual(rows.filter(r=>r.kind==='add').map(r=>r.text),['new']);
assert.deepEqual(diff('same\r\n','same\n'),[]);
assert.equal(rows.find(r=>r.kind==='add').newLine,2);
assert.equal(applicationIssue({changes:[{operation:'modify',conflict:false}]}),null);
assert.equal(applicationIssue({changes:[{conflict:false}]}),null);
assert.match(applicationIssue({changes:[{operation:'create'}]}),/not available yet/);
assert.match(applicationIssue({changes:[{operation:'delete'}]}),/live files are unchanged/);
assert.match(applicationIssue({changes:[{operation:'modify',conflict:true}]}),/conflict/);
assert.deepEqual(diff('','new','create'),[{kind:'add',newLine:1,text:'new'}]);
assert.deepEqual(diff('gone','','delete'),[{kind:'remove',oldLine:1,text:'gone'}]);
assert.deepEqual(diff('','','create'),[]);
console.log('Review normalization, path comparison and changed-line display checks passed.');
